#!/usr/bin/env python3
"""Export audited figure numbers, never manuscript prose, from rebuilt local data."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("docs/technical-report/latex/figure-data.tex")


def tex_escape(value: str) -> str:
    escapes = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(escapes.get(char, char) for char in value)


def count_ingest_sources(root: Path) -> tuple[int, int]:
    """Count the discovery ingest surface: direct connectors plus first-party feeds.

    The connector inventory lives in code and config rather than in the exported
    JSON, so it is read from the definitions themselves. `fetch_first_party_feeds`
    is a loop over the configured allowlist, not a source of its own, so it is
    excluded in favour of the individual feeds it fetches.
    """
    module = ast.parse((root / "src/benchmark_radar/sources.py").read_text(encoding="utf-8"))
    connectors = {
        node.name
        for node in module.body
        if isinstance(node, ast.FunctionDef) and node.name.startswith("fetch_")
    }
    connectors.discard("fetch_first_party_feeds")

    config = yaml.safe_load((root / "config.yml").read_text(encoding="utf-8"))
    feeds = (config.get("sources") or {}).get("first_party_feeds", {}).get("feeds") or []
    if not connectors or not feeds:
        raise ValueError("Could not resolve the discovery ingest surface")
    return len(connectors), len(feeds)


def render_data(root: Path) -> str:
    inputs = ("site/data/benchmark-index.json", "site/data/radar.json")
    raw = [(root / name).read_bytes() for name in inputs]
    index, radar = [json.loads(payload) for payload in raw]
    records = index["benchmarks"]
    sources = Counter(record["source"] for record in records)
    if index["count"] != len(records) or len({row["key"] for row in records}) != len(records):
        raise ValueError("Catalog count or source-record IDs do not reconcile")
    if len(records) < 1259 or len(sources) < 4:
        raise ValueError("Investigate corpus coverage: expected 1,259+ records across 4+ sources")

    corpus = radar["corpus"]
    observations = corpus["observations"]
    if corpus["observation_count"] != len(observations):
        raise ValueError("Corpus observation count does not reconcile")
    counts = Counter(row["source"] for row in observations)
    # Deterministic ties; the remainder includes every other normalized label.
    ordered = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
    bars = ordered[:5]
    if len(ordered) > 5:
        bars.append((f"{len(ordered) - 5} other labels", sum(n for _, n in ordered[5:])))
    if sum(value for _, value in bars) != len(observations) or not bars:
        raise ValueError("Source bars must account for the entire discovery corpus")
    artifacts = sum(entity["type"] == "artifact" for entity in corpus["entities"])
    connector_count, feed_count = count_ingest_sources(root)
    values = {
        "ReportDataCutoff": radar["latest_date"],
        "ReportObservationCount": len(observations),
        "ReportArtifactCount": artifacts,
        "ReportSnapshotCount": radar["snapshot_count"],
        "ReportCatalogCount": len(records),
        "ReportCatalogSourceCount": len(sources),
        "ReportConnectorCount": connector_count,
        "ReportFirstPartyFeedCount": feed_count,
        "ReportIngestSourceCount": connector_count + feed_count,
        "ReportLLMStatsCount": sources["llm_stats"],
        "ReportOpenCompassCount": sources["opencompass_hub"],
        "ReportArtificialAnalysisCount": sources["artificial_analysis"],
        "ReportModelReportCount": sources["model_reports"],
        "ReportSourceMaximum": max(value for _, value in bars),
    }
    lines = [
        "% Generated by scripts/export_report_figure_data.py; do not hand-edit.",
        "% Dated figure inputs, not a second source of manuscript prose.",
    ]
    for name, payload in zip(inputs, raw, strict=True):
        lines.append(f"% {name} SHA-256: {hashlib.sha256(payload).hexdigest()}")
    lines.extend(rf"\newcommand{{\{name}}}{{{value}}}" for name, value in values.items())
    lines.append(r"\newcommand{\ReportSourceBars}{%")
    lines.extend(
        rf"  \SourceBar{{{i}}}{{{tex_escape(label)}}}{{{value}}}%"
        for i, (label, value) in enumerate(bars)
    )
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="Fail if the dated inputs differ")
    args = parser.parse_args()
    result = render_data(args.root)
    output = args.root / OUTPUT
    if args.check:
        if output.read_text(encoding="utf-8") != result:
            raise SystemExit("Figure data differs; audit the rebuilt inputs before refreshing")
    else:
        output.write_text(result, encoding="utf-8")
        print(f"Wrote {output}")


if __name__ == "__main__":
    main()
